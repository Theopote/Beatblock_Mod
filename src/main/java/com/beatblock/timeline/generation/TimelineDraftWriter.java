package com.beatblock.timeline.generation;

import com.beatblock.BeatBlock;
import com.beatblock.runtime.BeatBlockContext;
import com.beatblock.timeline.AnimationEventParams;
import com.beatblock.timeline.Timeline;
import com.beatblock.timeline.TimelineAnimationEvent;
import com.beatblock.timeline.TimelineEventOrigin;
import com.beatblock.timeline.command.AddTimelineAnimationEventCommand;
import com.beatblock.timeline.command.ClearAnimationTrackCommand;
import com.beatblock.timeline.command.CommandManager;
import com.beatblock.timeline.editing.TimelineDocumentChangeNotifier;

import org.jspecify.annotations.Nullable;

import java.util.List;
import java.util.Map;

/**
 * Timeline animation-event write paths via {@link CommandManager}.
 * <p>
 * Use {@link #writeUserEvents} for UI-triggered committed inserts (Animation Library,
 * Event Library, record mode) — those notify {@link TimelineDocumentChangeNotifier}.
 * Use {@link #writeGeneratedEvents} for draft / auto-generation internal writes that
 * must not fire document-change side effects by themselves.
 */
public final class TimelineDraftWriter {

	private TimelineDraftWriter() {}

	public static int writeAutoGeneratedEvents(
		Timeline timeline,
		List<TimelineAnimationEvent> events,
		boolean replaceExisting
	) {
		if (timeline == null || events == null || events.isEmpty()) return 0;
		if (replaceExisting) {
			clearTrack(timeline, Timeline.TRACK_ID_ANIMATION_AUTO);
		}
		return writeGeneratedEvents(timeline, Timeline.TRACK_ID_ANIMATION_AUTO, events, TimelineEventOrigin.GENERATED);
	}

	public static void clearTrack(Timeline timeline, String trackId) {
		if (timeline == null || trackId == null) return;
		CommandManager commands = commandManagerOrNull();
		if (commands != null) {
			commands.execute(new ClearAnimationTrackCommand(timeline, trackId));
		} else {
			timeline.clearAnimationTrack(trackId);
		}
	}

	/**
	 * UI-triggered committed insertion. Notifies document change when at least one event is written.
	 */
	public static boolean writeUserEvent(
		Timeline timeline,
		String trackId,
		TimelineAnimationEvent event,
		TimelineEventOrigin origin
	) {
		if (event == null) return false;
		return writeUserEvents(timeline, trackId, List.of(event), origin) > 0;
	}

	/**
	 * UI-triggered committed insertion. Notifies document change once when {@code written > 0}.
	 */
	public static int writeUserEvents(
		Timeline timeline,
		String trackId,
		List<TimelineAnimationEvent> events,
		TimelineEventOrigin origin
	) {
		int written = writeEvents(timeline, trackId, events, origin != null ? origin : TimelineEventOrigin.MANUAL);
		if (written > 0) {
			TimelineDocumentChangeNotifier.notifyDocumentEdited();
		}
		return written;
	}

	/**
	 * Draft / auto-generation internal write. Does not notify document change.
	 */
	public static int writeGeneratedEvents(
		Timeline timeline,
		String trackId,
		List<TimelineAnimationEvent> events,
		TimelineEventOrigin origin
	) {
		return writeEvents(timeline, trackId, events, origin != null ? origin : TimelineEventOrigin.GENERATED);
	}

	/**
	 * Low-level single-event write (no document-change notify). Prefer
	 * {@link #writeUserEvent} or {@link #writeGeneratedEvents}.
	 */
	public static boolean writeEvent(
		Timeline timeline,
		String trackId,
		TimelineAnimationEvent event,
		TimelineEventOrigin origin
	) {
		if (timeline == null || trackId == null || event == null) return false;
		TimelineAnimationEvent tagged = event;
		TimelineGenerationMetadata existing = TimelineGenerationMetadata.fromParameters(event.getParameters());
		if (existing.generatorId().isBlank() && existing.generationId().isBlank()) {
			tagged = withOrigin(event, origin != null ? origin : TimelineEventOrigin.GENERATED);
		}
		if (tagged == null) return false;
		CommandManager commands = commandManagerOrNull();
		if (commands != null) {
			commands.execute(new AddTimelineAnimationEventCommand(timeline, trackId, tagged));
		} else {
			timeline.addAnimationEvent(trackId, tagged);
		}
		return true;
	}

	/**
	 * Low-level batch write (no document-change notify). Prefer
	 * {@link #writeUserEvents} or {@link #writeGeneratedEvents}.
	 */
	public static int writeEvents(
		Timeline timeline,
		String trackId,
		List<TimelineAnimationEvent> events,
		TimelineEventOrigin origin
	) {
		if (timeline == null || trackId == null || events == null || events.isEmpty()) return 0;
		int count = 0;
		for (TimelineAnimationEvent event : events) {
			if (writeEvent(timeline, trackId, event, origin)) count++;
		}
		if (count > 0) timeline.sortAll();
		return count;
	}

	public static @Nullable TimelineAnimationEvent withOrigin(
		@Nullable TimelineAnimationEvent source,
		@Nullable TimelineEventOrigin origin
	) {
		if (source == null) return null;
		TimelineEventOrigin resolved = origin != null ? origin : TimelineEventOrigin.GENERATED;
		return withMetadata(source, TimelineGenerationMetadata.fromOrigin(resolved));
	}

	public static @Nullable TimelineAnimationEvent withMetadata(
		@Nullable TimelineAnimationEvent source,
		@Nullable TimelineGenerationMetadata metadata
	) {
		if (source == null) return null;
		Map<String, Object> params = TimelineGenerationMetadataSupport.apply(
			AnimationEventParams.fromAnimationEvent(source).toParameterMap(),
			metadata
		);
		AnimationEventParams parsed = AnimationEventParams.fromParameterMap(params);
		return new TimelineAnimationEvent(
			source.getEventId(),
			source.getTimeSeconds(),
			parsed.durationSeconds(),
			parsed.animationType(),
			parsed.targetObject(),
			parsed.energy(),
			parsed.toParameterMap()
		);
	}

	private static @Nullable CommandManager commandManagerOrNull() {
		return commandManagerOrNull(BeatBlock.getContext());
	}

	static @Nullable CommandManager commandManagerOrNull(@Nullable BeatBlockContext context) {
		if (context == null) return null;
		return context.commandManager();
	}
}
